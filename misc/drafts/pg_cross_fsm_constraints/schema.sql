begin
;
create type order_state as enum(
    'start',
    'pending',
    'confirmed',
    'paid',
    'shipped',
    'delivered',
    'cancelled', -- cancelled before shipment
    'refunded', --refunded after delivery
    'error'
);

create type order_event as enum(
    'create',
    'confirm',
    'mark_paid',
    'mark_shipped',
    'mark_delivered',
    'cancel',
    'refund'
);


create table order_transitions(
    state order_state not null,
    event order_event not null,
    next_state order_state not null,
    primary key(state, event)
);

insert into order_transitions values
    ('start',     'create',         'pending'),
    ('pending',   'confirm',        'confirmed'),
    ('pending',   'cancel',         'cancelled'),
    ('confirmed', 'mark_paid',      'paid'),
    ('confirmed', 'cancel',         'cancelled'),
    ('paid',      'mark_shipped',   'shipped'),
    ('paid',      'cancel',         'cancelled'),  -- cancel before ship, triggers refund
    ('shipped',   'mark_delivered', 'delivered'),
    ('delivered', 'refund',         'refunded');

create type payment_state as enum(
    'start',
    'pending', -- waiting for customer action
    'processing', -- submmitted to processor, waiting for payment processor response
    'succeeded', -- money received (terminal)
    'failed', -- payment failed, (terminal)
    'cancelled', -- cancelled before completion (terminal)
    'refunded', -- money returned (terminal)
    'error'  -- invalid transition
);

create type payment_event as enum(
    'create',
    'submit',
    'succeed',
    'fail',
    'cancel',
    'expire',
    'refund'
);


create table payment_transitions(
    state payment_state not null,
    event payment_event not null,
    next_state payment_state not null,
    primary key(state, event)
);

insert into payment_transitions values
    ('start',      'create',  'pending'),     -- payment initiated, awaiting customer
    ('pending',    'submit',  'processing'),  -- customer finished, submitted to processor
    ('pending',    'cancel',  'cancelled'),   -- cancelled while waiting for customer
    ('pending',    'expire',  'failed'),      -- customer took too long
    ('processing', 'succeed', 'succeeded'),   -- processor confirmed
    ('processing', 'fail',    'failed'),      -- processor rejected
    ('succeeded',  'refund',  'refunded');  -- money returned to customer
-- ============================================================================
-- ---------------------------------- ORDER -----------------------------------
-- ============================================================================
create table orders(
    id bigint primary key generated by default as identity,
    customer_id bigint not null,
    total_amount numeric(12,2) not null,
    created_at timestamptz not null default now()
);

create table order_events(
    id bigint generated always as identity primary key,
    order_id int not null references orders(id),
    event order_event not null,
    state order_state not null, -- state AFTER event
    metadata jsonb default '{}',
    occured_at timestamptz default now() not null
);

create index idx_order_events_order_id_id_desc
    on order_events(order_id, id desc);

create function order_transition(_state order_state, _event order_event)
returns order_state
language sql
stable
parallel safe
as $$
select coalesce(
  (select next_state from order_transitions
        where state=_state and event=_event),
  'error'::order_state
);
$$
;

create function order_events_trigger_func()
returns trigger
language plpgsql
as
    $$
declare
  current_state order_state;
  next_state order_state;
  payment_state payment_state;
begin
    -- lock the parent order row which always exists
    perform 1 from orders where id = NEW.order_id for update;

    -- get current state
    select state into current_state
    from order_events
    where order_id = NEW.order_id
    order by id desc;

    -- if no prev event exists for this order then we're in start state
    if current_state is null then
      current_state := 'start'::order_state;
    end if;

    -- calculate the next state based on curr state and new event
    next_state := order_transition(current_state, NEW.event);

    -- validate the transition
    if next_state = 'error'::order_state then
        raise exception 'invalid order event: % is not valid from state %',
        NEW.event, current_state;
    end if;

    -- Cross-FSM Guard
    if NEW.event = 'mark_paid' then
        select pe.state into payment_state
        from payments p
        join payment_events pe on pe.payment_id = p.id
        where p.order_id = NEW.order_id
        order by pe.id desc limit 1;

        if payment_state is distinct from 'succeeded' then
            raise exception 'cannot set order to paid: no succeeded payment (got: %)', payment_state;
        end if;
    end if;

    -- automatically set the state s.t. users only need to provide the event
    NEW.state := next_state;
    return new;
end
$$
;


create trigger trg_before_insert_order_events before insert on order_events
for each row execute procedure order_events_trigger_func();

-- ============================================================================
-- ---------------------------------- PAYMENT ---------------------------------
-- ============================================================================
create table payments(
    id bigint primary key generated by default as identity,
    order_id bigint not null references orders(id),
    amount numeric(12,2) not null,
    metadata jsonb default '{}',
    created_at timestamptz not null default now()
);

create table payment_events(
    id bigint generated always as identity primary key,
    payment_id int not null references payments(id),
    event payment_event not null,
    state payment_state not null, -- denormalized: stores the resultant state after this event occured
    occured_at timestamptz default now() not null
);

create index idx_payment_events_payment_id_id_desc
    on payment_events(payment_id, id desc);

create function payment_transition(_state payment_state, _event payment_event)
returns payment_state
language sql
stable
parallel safe
as $$
select coalesce(
  (select next_state from payment_transitions
        where state=_state and event=_event),
  'error'::payment_state
);
$$
;

create function payment_events_trigger_func()
returns trigger
language plpgsql
as
    $$
declare
  current_state payment_state;
  next_state payment_state;
  v_order_state order_state;
  v_order_id bigint;
begin
    -- lock the parent payment row which always exists
    perform 1 from payments where id = NEW.payment_id for update;

    -- get current state
    select state into current_state
    from payment_events
    where payment_id = NEW.payment_id
    order by id desc;

    -- if no prev event exists for this payment then we're in start state
    if current_state is null then
      current_state := 'start'::payment_state;
    end if;

    -- calculate the next state based on curr state and new event
    next_state := payment_transition(current_state, NEW.event);

    -- validate the transition
    if next_state = 'error'::payment_state then
        raise exception 'invalid payment event: % is not valid from state %',
        NEW.event, current_state;
    end if;

    -- CROSS-FSM Guard: payment creation requires confirmed order
    if NEW.event = 'create' then
        -- get current state of order
        select p.order_id into v_order_id
        from payments p where p.id = NEW.payment_id;

        select oe.state into v_order_state
        from order_events oe
        where oe.order_id = v_order_id
        order by oe.id desc limit 1;

        if v_order_state is distinct from 'confirmed' then
            raise exception 'cannot create payment: order not confirmed (got: %)', v_order_state;
        end if;
    end if;

    -- automatically set the state s.t. users only need to provide the event
    NEW.state := next_state;
    return new;
end
$$
;


create trigger trg_before_insert_payment_events before insert on payment_events
for each row execute procedure payment_events_trigger_func();

commit
;
